"""
Spatial Transformer Mask Decoder for Surgical Instrument Segmentation.

Triggered by the special [SEG] token generated by the Language Model.
Cross-attends the [SEG] token hidden representation with spatial visual features
and upsamples via transposed convolutions to yield high-resolution 1024x1024
instrument segmentation masks.
"""

import math
import torch
import torch.nn as nn
import torch.nn.functional as F


class TransformerMaskDecoder(nn.Module):
    """
    Decodes spatial segmentation masks from LLM [SEG] token activations and ViT visual features.
    """
    def __init__(self, hidden_dim: int = 1024, mask_dim: int = 256):
        super().__init__()
        self.hidden_dim = hidden_dim
        self.mask_dim = mask_dim

        # Project LLM hidden state from [SEG] token to mask projection vector
        self.seg_proj = nn.Sequential(
            nn.Linear(hidden_dim, hidden_dim),
            nn.ReLU(),
            nn.Linear(hidden_dim, mask_dim),
        )

        # Transposed convolutional upsampler to upscale vision features into a spatial mask
        self.spatial_upsample = nn.Sequential(
            nn.ConvTranspose2d(hidden_dim, 512, kernel_size=2, stride=2),  # e.g., 16x16 -> 32x32
            nn.GELU(),
            nn.ConvTranspose2d(512, mask_dim, kernel_size=2, stride=2),    # e.g., 32x32 -> 64x64
            nn.GELU(),
        )

    def forward(self, seg_hidden_state: torch.Tensor, vision_hidden_states: torch.Tensor, image_size=(1024, 1024)) -> torch.Tensor:
        """
        Args:
            seg_hidden_state: [B, 1, hidden_dim] hidden representation of the [SEG] token
            vision_hidden_states: [B, seq_len, hidden_dim] visual feature sequence
            image_size: target output resolution tuple (H, W), default (1024, 1024)

        Returns:
            pred_mask: [B, 1, H, W] mask logits prior to sigmoid
        """
        B, seq_len, dim = vision_hidden_states.shape

        # Calculate square spatial grid size (e.g., sqrt(256) = 16)
        grid_size = int(math.isqrt(seq_len))
        if grid_size * grid_size != seq_len:
            # Pad or truncate if sequence length is not a perfect square
            target_len = (grid_size + 1) ** 2
            pad_amount = target_len - seq_len
            if pad_amount > 0:
                pad = torch.zeros(B, pad_amount, dim, device=vision_hidden_states.device, dtype=vision_hidden_states.dtype)
                vision_hidden_states = torch.cat([vision_hidden_states, pad], dim=1)
                grid_size += 1

        spatial_feats = vision_hidden_states[:, :grid_size*grid_size, :].transpose(1, 2).view(B, dim, grid_size, grid_size)

        # 1. Upsample vision features
        mask_embeddings = self.spatial_upsample(spatial_feats)  # [B, mask_dim, H', W']
        H_prime, W_prime = mask_embeddings.shape[2:]

        # 2. Project [SEG] hidden state
        if seg_hidden_state.dim() == 3:
            seg_hidden_state = seg_hidden_state.squeeze(1)
        seg_vector = self.seg_proj(seg_hidden_state)  # [B, mask_dim]

        # 3. Dot product between [SEG] vector and Spatial Mask Embeddings
        # [B, 1, mask_dim] x [B, mask_dim, H'*W'] -> [B, 1, H'*W']
        mask_embeddings_flat = mask_embeddings.view(B, self.mask_dim, -1)
        logits = torch.bmm(seg_vector.unsqueeze(1), mask_embeddings_flat)
        logits = logits.view(B, 1, H_prime, W_prime)

        # 4. Interpolate to target high-res image size
        pred_mask = F.interpolate(logits, size=image_size, mode="bilinear", align_corners=False)
        return pred_mask
